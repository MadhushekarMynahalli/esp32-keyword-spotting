"""Step 3: turn the trained model + DSP tables into C headers for the ESP32 sketch."""
import json, sys
import numpy as np
from config import *
from features import HANN, MEL


def cfloat(x):
    s = f"{float(x):.9g}"
    if not any(c in s for c in ".eEn"):      # "0" / "1" -> "0.0" / "1.0"  ("0f" is not valid C++)
        s += ".0"
    return s + "f"


def floats(a, per=8):
    v = [cfloat(x) for x in np.asarray(a).ravel()]
    return ",\n  ".join(", ".join(v[i:i + per]) for i in range(0, len(v), per))


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else FW_DIR
    out.mkdir(parents=True, exist_ok=True)
    norm = json.load(open(ART_DIR / "norm.json"))
    model = (ART_DIR / "kws_int8.tflite").read_bytes()

    with open(out / "kws_config.h", "w") as f:
        f.write("// AUTO-GENERATED by 03_export_headers.py -- do not edit\n#pragma once\n")
        for k, v in dict(SR=SR, WIN=WIN, HOP=HOP, NFFT=NFFT, NMEL=NMEL, NFRAMES=NFRAMES, NCLASS=len(LABELS)).items():
            f.write(f"#define KWS_{k} {v}\n")
        f.write("static const char* const kLabels[KWS_NCLASS] = {" + ", ".join(f'"{l}"' for l in LABELS) + "};\n")
        f.write(f"static const float kNormMean = {cfloat(norm['mean'])};\nstatic const float kNormStd = {cfloat(norm['std'])};\n")
        f.write(f"static const float kHann[KWS_WIN] = {{\n  {floats(HANN)}\n}};\n")
        f.write(f"static const float kMel[KWS_NMEL][KWS_NFFT/2+1] = {{\n  {floats(MEL, 9)}\n}};\n")

    with open(out / "model_data.h", "w") as f:
        f.write("// AUTO-GENERATED by 03_export_headers.py -- do not edit\n#pragma once\n")
        f.write("alignas(16) const unsigned char g_model[] = {\n  ")
        f.write(",\n  ".join(", ".join(f"0x{b:02x}" for b in model[i:i + 12]) for i in range(0, len(model), 12)))
        f.write(f"\n}};\nconst unsigned int g_model_len = {len(model)};\n")
    print(f"wrote {out/'kws_config.h'} and {out/'model_data.h'} ({len(model)/1024:.1f} KB model)")
